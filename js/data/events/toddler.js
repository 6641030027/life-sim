const o = (p, text, fx) => ({ p: p, text: text, fx: fx || {} });
const auto = (outcomes) => [{ label: 'ดูว่าเกิดอะไรขึ้น', auto: true, outcomes: outcomes }];

// เด็กทำได้ตามที่ตั้งใจแค่ไหน (ยิ่งโตยิ่งคุมได้)
const ctrl = (c) => [0.45, 0.6, 0.78][Math.max(0, Math.min(2, c.age - 2))];
const sum = (arr, c) => arr.reduce((a, x) => a + Math.max(0, txt(x.p, c)), 0) || 1;
// ตัวเลือกแบบทำเอง: intended = ผลเมื่อทำได้ตามตั้งใจ, slip = ผลเมื่อคุมตัวเองไม่อยู่ (ไม่ใส่ = ทำได้ตามตั้งใจเสมอ)
function mine(label, tags, intended, slip) {
  if (!slip) { return { label: label, tags: tags, outcomes: intended }; }
  const a = intended.map((x) => Object.assign({}, x, { p: (c) => txt(x.p, c) / sum(intended, c) * ctrl(c) }));
  const b = slip.map((x) => Object.assign({}, x, { p: (c) => txt(x.p, c) / sum(slip, c) * (1 - ctrl(c)) }));
  return { label: label, tags: tags, outcomes: a.concat(b) };
}
